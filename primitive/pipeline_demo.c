#include "pipeline.h"
#include <stdio.h>
#include <string.h>

/* ================================================================
 * 流水线状态可视化 — 打印某一时刻五级各在处理什么
 * ================================================================ */
static void print_pipeline(const PipelineCPU* c, int t) {
    const char* op_if = c->ifid_valid   ? stage_name(c->ifid_ins.opcode) : "  ";
    const char* op_id = c->idex_valid   ? stage_name(c->idex_ins.opcode) : "  ";
    const char* op_ex = c->exmem_valid  ? stage_name(c->exmem_ins.opcode) : "  ";
    const char* op_mw = c->memwb_valid  ? stage_name(c->memwb_ins.opcode) : "  ";

    printf("  周期 %2d │  IF %-3s │  ID %-3s │  EX %-3s │  MEM %-3s │  WB %-3s │ PC=%02X\n",
           t, op_if, op_id, op_ex, op_mw, op_mw, (unsigned)c->pc);
}

/* ================================================================
 * 演示 1: 单周期 vs 流水线 — 吞吐对比
 *
 * 程序 (5 条, 理想无冒险):
 *   LW R1; LW R2; ADD R3,R1,R2; SW mem,R3; HLT
 * 单周期: 每条指令 1 周期 + 1 周期启动 = 6 周期
 * 流水线: 5 条指令理想 5 + (5-1) 启动 = 9 周期, 吞吐 ≈ 每周期 0.56 条
 * ================================================================ */
static void demo_vs_single_cycle(void) {
    printf("\n╔══════════════════════════════════════════════════════════╗\n");
    printf("║  演示 1: 单周期 vs 流水线 — 吞吐率对比                   ║\n");
    printf("╚══════════════════════════════════════════════════════════╝\n\n");

    PipelineCPU c;
    pipeline_init(&c);
    c.mem[12] = 5; c.mem[13] = 3;
    Ins prog[] = {
        {OP_LW, 1,0,0,12},   /* R1 = mem[12] = 5 */
        {OP_LW, 2,0,0,13},   /* R2 = mem[13] = 3 */
        {OP_ADD,3,1,2,0},    /* R3 = R1+R2 = 8 */
        {OP_SW, 0,0,3,14},   /* mem[14] = R3 = 8 */
        {OP_HLT,0,0,0,0},
    };
    pipeline_load(&c, prog, 5);
    pipeline_run(&c, 100);

    int pip_cycles = c.cycles;
    int n_instr   = 4;               /* 有效指令数 (不含 HLT) */

    printf("  程序: LW R1 ← LW R2 ← ADD R3 ← SW mem ← (5 条指令)\n\n");
    printf("  【单周期 CPU】\n");
    printf("    每条指令需 1 个周期, 但硬件单元(ALU/内存)每周期只服务 1 条\n");
    printf("    总周期 = %d 条 × 1 = %d 周期, 吞吐率 = %.2f 条/周期\n\n",
           n_instr, n_instr, 1.0);

    printf("  【流水线 CPU】\n");
    printf("    5 级并行推进, 理想每周期完成 1 条\n");
    printf("    实际周期 = %d (含 %d 次冒险停顿 %d 次冲刷)\n",
           pip_cycles, c.stalls, c.flushes);
    printf("    吞吐率 = %.2f 条/周期  (R1=%d R2=%d R3=%d mem[14]=%d)\n\n",
           (double)n_instr / pip_cycles,
           c.reg[1], c.reg[2], c.reg[3], c.mem[14]);

    printf("  💡 结论: 流水线让多条指令「同步」占用不同硬件单元,\n");
    printf("     理想情况吞吐提升到接近 1 条/周期 (单周期的倍数)。\n");
    printf("     冒险(数据依赖/分支)会产生气泡, 这是流水线的「税」。\n");
}

/* ================================================================
 * 演示 2: 五级流水线逐周期流转 (可视化)
 * ================================================================ */
static void demo_pipeline_timeline(void) {
    printf("\n╔══════════════════════════════════════════════════════════╗\n");
    printf("║  演示 2: 五级流水线逐周期流转                             ║\n");
    printf("╚══════════════════════════════════════════════════════════╝\n\n");

    PipelineCPU c;
    pipeline_init(&c);
    c.mem[12] = 50;  /* R1 输入 */
    c.mem[13] = 7;   /* R2 输入 */

    Ins prog[] = {
        {OP_LW,  1,0,0,12},   /* 0: LW  R1, R0, 12  → R1 = 50 */
        {OP_LW,  2,0,0,13},   /* 1: LW  R2, R0, 13  → R2 = 7 */
        {OP_ADD, 3,1,2,0},    /* 2: ADD R3, R1, R2  → R3 = 57 */
        {OP_SUB, 4,3,1,0},    /* 3: SUB R4, R3, R1  → R4 = 7 */
        {OP_SW,  0,0,4,14},   /* 4: SW  mem[14] = R4 */
        {OP_J,   0,0,0,7},    /* 5: J  pc7 */
        {OP_ADD, 5,0,0,0},    /* 6: (应被跳过的垃圾) */
        {OP_HLT, 0,0,0,0},    /* 7: HLT */
    };
    pipeline_load(&c, prog, 8);
    printf("  时间轴 (运行 20 个周期, 观察指令如何在五级中流动):\n\n");
    printf("  五级: IF(取指) → ID(译码读操作数) → EX(执行) → MEM(访存) → WB(写回)\n\n");
    printf("  ┌──────── 逐周期快照 ────────\n");
    for (int t = 0; t < 20 && !c.halted; t++) {
        print_pipeline(&c, t);
        pipeline_clock(&c);
    }
    printf("  └────────────────────────────\n\n");

    printf("  结果: R1=%d R2=%d R3=%d R4=%d mem[14]=%d\n",
           c.reg[1], c.reg[2], c.reg[3], c.reg[4], c.mem[14]);
    printf("  说明:\n");
    printf("    - 观察多条指令「重叠」在不同阶段 → 这就是并行的本质\n");
    printf("    - ADD R3 依赖 R1,R2 (旁路解决), SUB 依赖 R3 (旁路)\n");
    printf("    - J 指令触发了分支冲刷 (IF/ID 被清空, 指令6被丢弃)\n");
    printf("    - SW 写内存段在 MEM 阶段完成\n");
}

/* ================================================================
 * 演示 3: 冒险 - 停顿 / 旁路 / 冲刷 统计
 * ================================================================ */
static void demo_hazards(void) {
    printf("\n╔══════════════════════════════════════════════════════════╗\n");
    printf("║  演示 3: 三类冒险 — 停顿 / 旁路 / 冲刷                    ║\n");
    printf("╚══════════════════════════════════════════════════════════╝\n\n");

    PipelineCPU c;
    pipeline_init(&c);
    c.mem[12] = 5; c.mem[13] = 3;
    Ins prog[] = {
        {OP_LW, 1,0,0,12},   /* R1=5 */
        {OP_LW, 2,0,0,13},   /* R2=3 */
        {OP_ADD,3,1,2,0},    /* R3 = R1+R2 (紧邻依赖 LW → load-use 停顿) */
        {OP_ADD,4,3,3,0},    /* R4 = R3+R3 (依赖上条 ADD → 旁路解决, 不停顿) */
        {OP_BEQ,0,4,5,2},    /* BEQ R4,R5? R4=16,R5=0 不等 → 不跳 (预测试错) */
        {OP_SW, 0,0,4,14},   /* mem[14] = R4 */
        {OP_HLT,0,0,0,0},
    };
    pipeline_load(&c, prog, 7);
    pipeline_run(&c, 100);

    printf("  程序: 两条 LW → 连续 ADD → BEQ → SW → HLT\n");
    printf("  ────────────────\n");
    printf("  统计结果:\n");
    printf("    总周期      = %d\n", c.cycles);
    printf("    旁路转发数  = %2d   (数据冒险被「偷偷」化解, 不产生气泡)\n", c.forwards);
    printf("    停顿次数    = %2d   (load-use, 插入气泡, 损失吞吐)\n", c.stalls);
    printf("    冲刷次数    = %2d   (分支, 丢弃已取错误指令, 损失吞吐)\n", c.flushes);
    printf("  ────────────────\n");
    printf("  最终值: R1=%d R2=%d R3=%d R4=%d mem[14]=%d\n",
           c.reg[1], c.reg[2], c.reg[3], c.reg[4], c.mem[14]);
    printf("\n  💡 冒险代价排序: 冲刷(2周期) > 停顿(1周期) > 旁路(0代价)\n");
    printf("     流水线设计的艺术, 就是用旁路化解大多数依赖,\n");
    printf("     尽量把昂贵的停顿和冲刷降到最少。\n");
}

/* ================================================================
 * 演示 4: 2-bit 分支预测器状态机
 * ================================================================ */
static void demo_bp_fsm(void) {
    printf("\n╔══════════════════════════════════════════════════════════╗\n");
    printf("║  演示 4: 2-bit 分支预测器 — 饱和计数器状态机              ║\n");
    printf("╚══════════════════════════════════════════════════════════╝\n\n");

    printf("  状态机 (2-bit 饱和计数器):\n");
    printf("\n               ┌──────────────┐\n");
    printf("        不跳来  │              │ 跳来\n");
    printf("      ┌────────►│  00  强不取   │◄────────┐\n");
    printf("      │         │              │         │\n");
    printf("      │         └──────┬───────┘         │\n");
    printf("      │  不跳          │ 跳              │ 跳\n");
    printf("      │                ▼                 │\n");
    printf("      │         ┌──────────────┐         │\n");
    printf("      │         │  01  弱不取   │         │\n");
    printf("      │         └──────┬───────┘         │\n");
    printf("      │  不跳          │ 跳              │ 跳\n");
    printf("      │                ▼                 │\n");
    printf("      │         ┌──────────────┐         │\n");
    printf("      │         │  10  弱取     │         │\n");
    printf("      │         └──────┬───────┘         │\n");
    printf("      │  不跳          │ 跳              │ 跳\n");
    printf("      │                ▼                 │\n");
    printf("      │         ┌──────────────┐         │\n");
    printf("      │         │  11  强取     │         │\n");
    printf("      │         └──────────────┘         │\n");
    printf("      │  不跳                              │ 跳\n");
    printf("      └───────────────────────────────────┘\n\n");

    printf("  为什么用 2-bit 而不是 1-bit?\n");
    printf("    1-bit 对「循环退出」分支极不友好: 循环体最后一次跳转和\n");
    printf("    第一次不跳都会误预测。2-bit 需要连续两次走反才改变方向,\n");
    printf("    能容忍少数扰动脉冲, 对「长期稳定」的分支保持高命中率.\n\n");

    printf("  在本演示中, 2-bit 预测器的状态由每次分支的实际方向更新\n");
    printf("  (命中=方向一致, 出错=方向相反并进入另一状态)。\n");
    printf("  预测器最终能否命中, 取决于分支的行为模式是否「稳定」.\n");
}

